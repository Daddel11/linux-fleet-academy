package com.fleetacademy.game;

import java.util.HashSet;
import java.util.Set;

public class ChapterOneRegression {
    static void check(boolean value, String message) { if (!value) throw new AssertionError(message); }
    static void run(SimShell s, String cmd) { s.run(cmd); }
    public static void main(String[] args) {
        Set<String> done = new HashSet<>();
        check(GameData.DOORS.get(0).gate && GameData.DOORS.get(0).needs[0].equals("crew"), "quarters gate");
        check(!GameData.DOORS.get(12).gate, "parallel missions reachable via corridor");
        check(GameData.DOORS.get(2).gate && GameData.DOORS.get(2).needs.length == 2, "engine room gate");
        check(GameData.DOORS.get(5).gate && GameData.DOORS.get(5).needs.length == 4, "navigation gate");
        SimShell locked = new SimShell(null, done);
        SimShell.Completion completion = locked.complete("sys", 3);
        check(completion.text.equals("systemctl ") && completion.cursor == 10, "command completion");
        completion = locked.complete("sudo ca", 7);
        check(completion.text.equals("sudo cat "), "sudo command completion");
        completion = locked.complete("cat /etc/systemd/sys", 20);
        check(completion.text.equals("cat /etc/systemd/system/engine.service "), "virtual path completion");
        completion = locked.complete("cat /etc/black", 14);
        check(completion.text.equals("cat /etc/blackstar/bulkhead.conf "), "restore destination completion");
        completion = locked.complete("c", 1);
        check(completion.text.equals("c") && completion.note.contains("cat") && completion.note.contains("cp") && completion.note.contains("clear"), "ambiguous candidates");
        locked.files().put("/var/backups/bulkhead.old", "virtual");
        completion = locked.complete("cat /var/b", 10);
        check(completion.text.equals("cat /var/backups/bulkhead.") && completion.note.contains("bulkhead.conf") && completion.note.contains("bulkhead.old"), "ambiguous path common prefix");
        locked.files().remove("/var/backups/bulkhead.old");
        completion = locked.complete("systemctl /etc/b", 16);
        check(completion.text.equals("systemctl /etc/blackstar/bulkhead.conf "), "path completion outside cat");
        completion = locked.complete("sys tail", 3);
        check(completion.text.equals("systemctl tail") && completion.cursor == 9, "cursor preserves suffix");
        completion = locked.complete("nonsense", 8);
        check(completion.text.equals("nonsense") && completion.cursor == 8 && completion.note.isEmpty(), "no match");
        completion = locked.complete("cat /not-real", 13);
        check(completion.text.equals("cat /not-real") && completion.note.isEmpty(), "no path match");
        check(locked.history.isEmpty() && locked.files().size() == 2, "completion has no side effects");
        run(locked, "systemctl start power-grid.service");
        check(locked.exitCode != 0 && !locked.power, "locked shared terminal action");
        run(locked, "systemctl list-units --type=service --all");
        run(locked, "systemctl status power-grid.service");
        check(locked.solved("crew"), "diagnosis allowed");
        check(GameData.available("crew", done) && !GameData.available("life", done), "initial gating");
        done.add("crew");
        check(GameData.available("life", done) && GameData.available("reactor", done) && GameData.available("canteen", done) && !GameData.available("medbay", done), "parallel missions");
        run(locked, "systemctl start power-grid.service");
        check(locked.power, "unlocked action");
        run(locked, "systemctl start engine.service");
        check(locked.exitCode != 0 && !locked.engine, "engine action locked");
        done.add("reactor"); done.add("canteen");
        check(GameData.available("medbay", done) && !GameData.available("fuel", done), "engine before navigation");
        Set<String> unlocked = new HashSet<>(java.util.Arrays.asList("crew", "reactor", "life", "canteen", "medbay"));
        SimShell s = new SimShell(null, unlocked);
        run(s, "systemctl isolate flight.target");
        check(s.exitCode != 0 && !s.flight && !s.power && !s.oxygen, "flight guard");
        run(s, "systemctl list-units --type=service --all");
        check(!s.solved("crew"), "diagnosis requires inspection");
        run(s, "systemctl status power-grid.service");
        check(s.solved("crew"), "diagnosis");
        run(s, "systemctl start oxygen.service");
        check(!s.solved("life"), "start alone");
        run(s, "systemctl enable oxygen.service");
        check(s.solved("life"), "separate enable");
        SimShell alt = new SimShell(null, unlocked);
        run(alt, "sudo systemctl enable --now oxygen.service");
        check(alt.solved("life"), "enable now");
        run(s, "systemctl restart bulkhead.service");
        check(!s.solved("canteen") && s.exitCode != 0, "missing config");
        run(s, "cp /var/backups/bulkhead.conf /etc/blackstar/bulkhead.conf");
        run(s, "systemctl restart bulkhead.service");
        run(s, "systemctl start power-grid.service");
        check(s.solved("canteen") && s.solved("reactor"), "repair services");
        s.editUnit(SimShell.INITIAL_UNIT.replace("[Unit]\n", "[Unit]\nAfter=power-grid.service\n"));
        run(s, "systemctl daemon-reload"); run(s, "systemctl start engine.service");
        check(!s.solved("medbay") && s.exitCode != 0, "After alone");
        s.editUnit(SimShell.INITIAL_UNIT.replace("[Unit]\n", "[Unit]\nAfter=power-grid.service\nRequires=power-grid.service\n"));
        run(s, "systemctl start engine.service");
        check(!s.solved("medbay"), "reload required");
        run(s, "systemctl daemon-reload"); run(s, "systemctl start engine.service");
        check(s.solved("medbay"), "engine repaired");
        s.editUnit(s.files().get(SimShell.ENGINE).replace("Type=simple", "Type=broken"));
        run(s, "systemctl daemon-reload"); run(s, "systemctl restart engine.service");
        check(!s.solved("medbay") && s.exitCode != 0, "invalid service type");
        s.editUnit(s.files().get(SimShell.ENGINE).replace("Type=broken", "Type=simple").replace("ExecStart=/opt/blackstar/bin/engine-control", "ExecStart=/wrong"));
        run(s, "systemctl daemon-reload"); run(s, "systemctl restart engine.service");
        check(!s.solved("medbay") && s.exitCode != 0, "invalid executable");
        s.editUnit(s.files().get(SimShell.ENGINE).replace("ExecStart=/wrong", "ExecStart=/opt/blackstar/bin/engine-control"));
        run(s, "systemctl daemon-reload"); run(s, "systemctl restart engine.service");
        check(s.solved("medbay"), "recover engine service");
        s.editUnit(s.files().get(SimShell.ENGINE) + "\n");
        run(s, "systemctl daemon-reload");
        check(!s.solved("medbay"), "edited engine must be restarted after reload");
        run(s, "systemctl isolate flight.target");
        check(s.exitCode != 0 && !s.flight, "flight requires current engine revision");
        run(s, "systemctl restart engine.service");
        check(s.solved("medbay"), "engine restarted after edit");
        run(s, "systemctl isolate flight.target");
        check(s.solved("fuel") && s.power && s.oxygen && s.bulkhead && s.engine, "flight preserves services");
        run(s, "systemctl start power-grid.service; reboot");
        check(s.exitCode != 0, "shell operators rejected");
        System.out.println("ChapterOneRegression: PASS");
    }
}
